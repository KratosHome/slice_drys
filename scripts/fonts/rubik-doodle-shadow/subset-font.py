"""Rebuild the disjoint Rubik faces from the pinned upstream TTF.

Manual maintenance only; Next.js never runs this script.
Run with Python 3.11+ and fontTools[woff] 4.66.1 from the repository root:
python scripts/fonts/rubik-doodle-shadow/subset-font.py /path/to/RubikDoodleShadow-Regular.ttf
"""

import hashlib
import io
import json
import sys
from pathlib import Path

from fontTools import subset
from fontTools.pens.recordingPen import DecomposingRecordingPen
from fontTools.ttLib import TTFont


ROOT = Path(__file__).parent
PROJECT_ROOT = ROOT.parents[2]
FONT_OUTPUT = PROJECT_ROOT / "public/fonts/rubik-doodle-shadow"
STYLE_OUTPUT = PROJECT_ROOT / "src/fonts"
METADATA = ROOT / "subset.json"
SOURCE_RANGES = (
    "U+0020-007E,U+00A0-00BF,U+00D7,U+00F7,U+0401,U+0404,U+0406-0407,"
    "U+0410-044F,U+0451,U+0454,U+0456-0457,U+0490-0491,U+2000-206F,"
    "U+20AC,U+20B4,U+2116,U+2122,U+2190-2193,U+2212,U+2215,U+FEFF,"
    "U+FFFD,U+0301,U+0308,U+02BB-02BC"
)
UI_SYMBOLS = set(map(ord, " \u00a0!\"'-<>\u02bb\u02bc\u2013\u2014\u2018\u2019\u201c\u201d\u2026"))


def unicode_ranges(codepoints):
    spans = []
    for code in sorted(codepoints):
        if spans and code == spans[-1][1] + 1:
            spans[-1][1] = code
        else:
            spans.append([code, code])
    return ",".join(
        f"U+{first:04X}" if first == last else f"U+{first:04X}-{last:04X}"
        for first, last in spans
    )


def write_browser_assets(faces, fallback):
    """Keep preload URLs and CSS sources identical, including their content hashes."""
    urls = {face["name"]: f'/fonts/rubik-doodle-shadow/{face["file"]}' for face in faces}
    (STYLE_OUTPUT / "rubik-doodle-shadow-assets.json").write_text(
        json.dumps(urls, indent=2) + "\n"
    )
    rules = ["/* Generated by scripts/fonts/rubik-doodle-shadow/subset-font.py. */"]
    for face in faces:
        rules.append(
            '@font-face {\n  font-family: "Rubik Doodle Shadow";\n'
            f'  src: url("{urls[face["name"]]}") format("woff2");\n'
            '  font-display: swap;\n  font-weight: 400;\n  font-style: normal;\n'
            f'  unicode-range: {face["unicodeRanges"]};\n}}'
        )
    rules.append(
        '@font-face {\n  font-family: "Rubik Doodle Shadow Fallback";\n'
        f'  src: local("{fallback["font"]}");\n'
        f'  ascent-override: {fallback["ascentOverride"]};\n'
        f'  descent-override: {fallback["descentOverride"]};\n'
        f'  line-gap-override: {fallback["lineGapOverride"]};\n'
        f'  size-adjust: {fallback["sizeAdjust"]};\n}}'
    )
    rules.append(
        '.font-rubik-doodle-shadow {\n  --font-rubik-doodle-shadow: '
        '"Rubik Doodle Shadow", "Rubik Doodle Shadow Fallback";\n}'
    )
    (STYLE_OUTPUT / "rubik-doodle-shadow.css").write_text("\n\n".join(rules) + "\n")


def main():
    source = Path(sys.argv[1])
    metadata = json.loads(METADATA.read_text())
    source_hash = hashlib.sha256(source.read_bytes()).hexdigest()
    if source_hash != metadata["sourceSha256"]:
        raise ValueError("Source SHA-256 differs from the pinned Google Fonts TTF")

    original = TTFont(source, recalcTimestamp=False)
    original_cmap = original.getBestCmap()
    supported = set(subset.parse_unicodes(SOURCE_RANGES)) & set(original_cmap)
    if len(supported) != 227:
        raise ValueError(f"Expected 227 supported characters, got {len(supported)}")

    cyrillic = {code for code in supported if 0x0400 <= code <= 0x052F}
    latin = {
        code for code in supported
        if 0x0041 <= code <= 0x005A or 0x0061 <= code <= 0x007A
    }
    ui = supported & UI_SYMBOLS
    groups = {
        "ui": ui,
        "cyrillic": cyrillic,
        "latin": latin,
        "punctuation": supported - ui - cyrillic - latin,
    }
    if set.union(*groups.values()) != supported:
        raise ValueError("Character coverage differs from the previous combined face")
    if sum(map(len, groups.values())) != len(supported):
        raise ValueError("CSS unicode ranges overlap")

    original_glyphs = original.getGlyphSet()
    outlines_changed = []
    advances_changed = []
    metric_changes = []
    faces = []

    for name, characters in groups.items():
        font = TTFont(source, recalcTimestamp=False)
        options = subset.Options()
        options.hinting = False
        options.layout_features = ["*"]
        options.name_IDs = ["*"]
        options.name_languages = ["*"]
        options.recalc_timestamp = False
        subsetter = subset.Subsetter(options=options)
        # Preserve the Latin asset used to derive the existing Arial fallback.
        # Its extra space glyph is excluded from this face's CSS range.
        asset_characters = characters | ({0x0020} if name == "latin" else set())
        subsetter.populate(unicodes=asset_characters)
        subsetter.subset(font)
        font.flavor = "woff2"
        buffer = io.BytesIO()
        font.save(buffer)
        asset = buffer.getvalue()
        asset_hash = hashlib.sha256(asset).hexdigest()
        filename = f"RubikDoodleShadow-{name}.{asset_hash[:12]}.woff2"
        output = FONT_OUTPUT / filename
        output.write_bytes(asset)

        rendered = TTFont(output)
        rendered_cmap = rendered.getBestCmap()
        if not characters <= set(rendered_cmap):
            raise ValueError(f"{name}: required glyphs missing")
        glyphs = rendered.getGlyphSet()
        for code in sorted(characters):
            before = DecomposingRecordingPen(original_glyphs)
            after = DecomposingRecordingPen(glyphs)
            original_glyphs[original_cmap[code]].draw(before)
            glyphs[rendered_cmap[code]].draw(after)
            if before.value != after.value:
                outlines_changed.append(f"{name}:{code:04X}")
            if original["hmtx"].metrics[original_cmap[code]] != rendered["hmtx"].metrics[rendered_cmap[code]]:
                advances_changed.append(f"{name}:{code:04X}")
        for table, fields in {
            "head": ["unitsPerEm"],
            "hhea": ["ascent", "descent", "lineGap"],
            "OS/2": ["sTypoAscender", "sTypoDescender", "sTypoLineGap", "usWinAscent", "usWinDescent"],
        }.items():
            for field in fields:
                if getattr(original[table], field) != getattr(rendered[table], field):
                    metric_changes.append(f"{name}:{table}.{field}")
        faces.append({
            "name": name,
            "file": filename,
            "unicodeRanges": unicode_ranges(characters),
            "characters": len(characters),
            "bytes": output.stat().st_size,
            "sha256": hashlib.sha256(output.read_bytes()).hexdigest(),
            "preloadLocales": ["uk", "en"] if name == "ui" else ["uk"] if name == "cyrillic" else ["en"] if name == "latin" else [],
            "assetExtraCharacters": ["U+0020"] if name == "latin" else [],
        })

    if outlines_changed or advances_changed or metric_changes:
        raise ValueError("Font rendering or metrics changed")

    metadata.update({
        "formatVersion": 3,
        "unicodeRanges": SOURCE_RANGES,
        "previousCombinedSubsetBytes": 281528,
        "subsetBytes": sum(face["bytes"] for face in faces),
        "faces": faces,
        "renderingVerification": {
            "decomposedOutlineChanges": 0,
            "advanceWidthChanges": 0,
            "verticalMetricsChanged": False,
            "checkedCharacters": len(supported),
            "cssRangesOverlap": False,
            "missingPreviousCharacters": [],
        },
        "fallbackMetrics": {
            "font": "Arial",
            "ascentOverride": "78.34%",
            "descentOverride": "20.95%",
            "lineGapOverride": "0.00%",
            "sizeAdjust": "119.36%",
        },
        "coverage": "The same 227 mapped characters as the previous combined UK/English font. CSS unicode ranges are disjoint; punctuation and digits stay available when needed. Latin retains the extra space glyph used to derive the unchanged Arial fallback metrics.",
        "rebuildCommand": "python scripts/fonts/rubik-doodle-shadow/subset-font.py /path/to/RubikDoodleShadow-Regular.ttf",
    })
    metadata.pop("subsetSha256", None)
    METADATA.write_text(json.dumps(metadata, ensure_ascii=False, indent=2) + "\n")
    write_browser_assets(faces, metadata["fallbackMetrics"])
    print(json.dumps({"faces": faces, "verification": metadata["renderingVerification"]}, indent=2))


if __name__ == "__main__":
    main()
